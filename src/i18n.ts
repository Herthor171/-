export function formatLak(amount: number, lang: Lang = 'lo'): string {
  const formatted = new Intl.NumberFormat('en-US').format(Math.round(amount || 0));
  return lang === 'lo' ? `${formatted} ກີບ` : `${formatted} LAK`;
}
